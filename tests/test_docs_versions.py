"""Controls for independent per-SDK documentation snapshots.

These run against an isolated fixture checkout with a stand-in for Docusaurus's
``docs:version`` command, so no test ever creates real release history.
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts import docs_versions
from scripts.docs_versions import SnapshotError, remove_snapshot, snapshot
from scripts.prepare_docs import _archives


def _root(tmp_path: Path) -> Path:
    (tmp_path / "website").mkdir()
    (tmp_path / "pyproject.toml").write_text('[project]\nversion = "1.2.3"\n', encoding="utf-8")
    props = tmp_path / "src" / "csharp" / "Directory.Build.props"
    props.parent.mkdir(parents=True)
    props.write_text(
        "<Project><PropertyGroup><Version>4.5.6-proof</Version></PropertyGroup></Project>",
        encoding="utf-8",
    )
    return tmp_path


def _prepare(root: Path) -> dict[str, object]:
    generated = root / "website" / ".generated"
    shutil.rmtree(generated, ignore_errors=True)
    pages = {
        "csharp/guides/csharp-sdk.md": (
            "# C#\n\n[API](/csharp/api/anyinfer.asyncclient/#member-1) "
            "[Shared](/concepts/targets/) [Python](/python/quickstart/) "
            '<a href="/csharp/reference/">reference</a> [Unknown](/csharp/not-a-page/)\n'
        ),
        "csharp/reference/csharp-sdk.md": "# Reference\n",
        "csharp/api/anyinfer.asyncclient.md": "# AsyncClient class\n",
        "python/guides/quickstart.md": "# Quickstart\n\n[C#](/csharp/)\n",
        "shared/concepts/targets.md": "# Targets\n",
    }
    for relative, text in pages.items():
        path = generated / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    manifest = {
        "pages": [
            {"source": "guides/csharp-sdk.md", "sdk": "csharp", "url": "/csharp/", "title": "C#"},
            {
                "source": "reference/csharp-sdk.md",
                "sdk": "csharp",
                "url": "/csharp/reference/",
                "title": "Reference",
            },
            {
                "source": "generated:csharp-api/T:AnyInfer.AsyncClient",
                "sdk": "csharp",
                "url": "/csharp/api/anyinfer.asyncclient/",
                "title": "AsyncClient class",
            },
            {
                "source": "guides/quickstart.md",
                "sdk": "python",
                "url": "/python/quickstart/",
                "title": "Quickstart",
            },
            {
                "source": "concepts/targets.md",
                "sdk": "shared",
                "url": "/concepts/targets/",
                "title": "Targets",
            },
        ],
    }
    (generated / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
    return manifest


def _docusaurus(command: list[str], website: Path) -> None:
    """Emulate `docusaurus docs:version:<sdk> <version>` for the multi-instance layout."""
    sdk = command[0].removeprefix("docs:version:")
    version = command[1]
    shutil.copytree(
        website / ".generated" / sdk,
        website / f"{sdk}_versioned_docs" / f"version-{version}",
    )
    sidebars = website / f"{sdk}_versioned_sidebars"
    sidebars.mkdir(exist_ok=True)
    (sidebars / f"version-{version}-sidebars.json").write_text(
        '{"navigation": [{"type": "autogenerated", "dirName": "."}]}', encoding="utf-8"
    )
    versions_path = website / f"{sdk}_versions.json"
    versions = (
        json.loads(versions_path.read_text(encoding="utf-8")) if versions_path.is_file() else []
    )
    versions_path.write_text(json.dumps([version, *versions]), encoding="utf-8")


def _symbols(_root: Path) -> dict[str, str]:
    return {
        "T:AnyInfer.AsyncClient": "/csharp/api/anyinfer.asyncclient/",
        "M:AnyInfer.AsyncClient.DisposeAsync": "/csharp/api/anyinfer.asyncclient/#member-1",
    }


def _files(root: Path) -> dict[str, bytes]:
    website = root / "website"
    return {
        path.relative_to(website).as_posix(): path.read_bytes()
        for path in website.rglob("*")
        if path.is_file() and ".generated" not in path.parts
    }


def test_snapshot_archives_prepared_pages_and_points_same_sdk_links_at_the_archive(
    tmp_path: Path,
) -> None:
    root = _root(tmp_path)
    archive = snapshot(
        root, "csharp", "4.5.6-proof", prepare=_prepare, docusaurus=_docusaurus, symbols=_symbols
    )

    assert archive == root / "website" / "csharp_versioned_docs" / "version-4.5.6-proof"
    overview = (archive / "guides" / "csharp-sdk.md").read_text(encoding="utf-8")
    assert "(/csharp/4.5.6-proof/api/anyinfer.asyncclient/#member-1)" in overview
    assert 'href="/csharp/4.5.6-proof/reference/"' in overview
    # Shared pages, the other SDK and unknown routes are left exactly as written.
    assert "(/concepts/targets/)" in overview and "(/python/quickstart/)" in overview
    assert "(/csharp/not-a-page/)" in overview
    # The generated API body is archived as rendered, with its manifest and symbol map.
    assert (archive / "api" / "anyinfer.asyncclient.md").read_text(
        encoding="utf-8"
    ) == "# AsyncClient class\n"
    assert (
        json.loads((archive / "manifest.json").read_text(encoding="utf-8"))["pages"][0]["url"]
        == "/csharp/"
    )
    assert json.loads((archive / "symbols.json").read_text(encoding="utf-8")) == {
        "M:AnyInfer.AsyncClient.DisposeAsync": "/csharp/4.5.6-proof/api/anyinfer.asyncclient/#member-1",
        "T:AnyInfer.AsyncClient": "/csharp/4.5.6-proof/api/anyinfer.asyncclient/",
    }
    assert docs_versions.archived_versions(root / "website", "csharp") == ["4.5.6-proof"]
    assert docs_versions.archived_versions(root / "website", "python") == []
    assert not (root / "website" / "python_versioned_docs").exists()


def test_one_sdks_snapshot_leaves_the_other_sdks_history_untouched(tmp_path: Path) -> None:
    root = _root(tmp_path)
    snapshot(root, "python", "1.2.3", prepare=_prepare, docusaurus=_docusaurus)
    python_history = {
        key: value for key, value in _files(root).items() if key.startswith("python_")
    }

    snapshot(
        root, "csharp", "4.5.6-proof", prepare=_prepare, docusaurus=_docusaurus, symbols=_symbols
    )
    after = {key: value for key, value in _files(root).items() if key.startswith("python_")}
    assert after == python_history

    def careless(command: list[str], website: Path) -> None:
        _docusaurus(command, website)
        (website / "python_versions.json").write_text('["1.2.3", "0.0.1"]', encoding="utf-8")

    remove_snapshot(root, "csharp", "4.5.6-proof")
    with pytest.raises(SnapshotError, match="changed the python version history"):
        snapshot(root, "csharp", "4.5.6-proof", prepare=_prepare, docusaurus=careless)


@pytest.mark.parametrize(
    ("sdk", "version", "match"),
    [
        ("csharp", "9.9.9", "describes 4.5.6-proof"),
        ("python", "1.2.4", "describes 1.2.3"),
        ("go", "1.0.0", "unknown SDK"),
        ("python", "latest", "not a release version"),
    ],
)
def test_snapshot_only_archives_the_outgoing_version(
    tmp_path: Path, sdk: str, version: str, match: str
) -> None:
    root = _root(tmp_path)
    with pytest.raises(SnapshotError, match=match):
        snapshot(root, sdk, version, prepare=_prepare, docusaurus=_docusaurus)
    assert _files(root) == {}


def test_a_version_cannot_be_archived_twice(tmp_path: Path) -> None:
    root = _root(tmp_path)
    snapshot(root, "python", "1.2.3", prepare=_prepare, docusaurus=_docusaurus)
    with pytest.raises(SnapshotError, match="already archived"):
        snapshot(root, "python", "1.2.3", prepare=_prepare, docusaurus=_docusaurus)


def test_remove_snapshot_restores_the_previous_history_exactly(tmp_path: Path) -> None:
    root = _root(tmp_path)
    snapshot(root, "python", "1.2.3", prepare=_prepare, docusaurus=_docusaurus)
    before = _files(root)
    snapshot(
        root, "csharp", "4.5.6-proof", prepare=_prepare, docusaurus=_docusaurus, symbols=_symbols
    )
    remove_snapshot(root, "csharp", "4.5.6-proof")
    assert _files(root) == before
    with pytest.raises(SnapshotError, match="is not archived"):
        remove_snapshot(root, "csharp", "4.5.6-proof")


def test_prepared_manifest_lists_archived_routes_for_search_and_exports(tmp_path: Path) -> None:
    root = _root(tmp_path)
    assert _archives(root) == {}
    snapshot(
        root, "csharp", "4.5.6-proof", prepare=_prepare, docusaurus=_docusaurus, symbols=_symbols
    )
    archives = _archives(root)
    assert list(archives) == ["csharp"]
    assert archives["csharp"][0]["version"] == "4.5.6-proof"
    assert [page["url"] for page in archives["csharp"][0]["pages"]] == [
        "/csharp/4.5.6-proof/",
        "/csharp/4.5.6-proof/reference/",
        "/csharp/4.5.6-proof/api/anyinfer.asyncclient/",
    ]
